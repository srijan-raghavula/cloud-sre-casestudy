"""
ML Anomaly Detector — Real-time Intrusion Detection (Config C)
Reference: Khan (2016) Case Study — Phase 3, Hybrid ML-IDPS

Implements lightweight Isolation Forest and Random Forest classifiers
for sub-50ms detection latency on network flow features.

Architecture:
  1. Reads Suricata eve.json logs in real-time
  2. Extracts flow features via FeaturePipeline
  3. Classifies traffic as benign/attack using trained model
  4. Issues iptables drop commands for high-confidence attacks

Models used:
  - Isolation Forest: Unsupervised anomaly detection (faster)
  - Random Forest: Supervised classification (higher accuracy)

Target latency: <50ms per flow classification
"""

