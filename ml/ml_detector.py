# Data Structures
# ─────────────────────────────────────────────────────────────
@dataclass
class FlowFeature:
    """Single flow feature record for ML classification."""

    flow_id: str
    timestamp: float
    duration_ms: float
    total_fwd_pkts: int
    total_bwd_pkts: int
    total_pkts: int
    flow_bytes_per_sec: float
    flow_packets_per_sec: float
    pkt_len_mean: float
    pkt_len_std: float
    flag_syn: int
    flag_ack: int
    flag_fin: int
    flag_rst: int
    flag_psh: int
    flag_urg: int
    label: str = "benign"  # benign, attack, unknown
    confidence: float = 0.0
    prediction: str = "unknown"
    detection_time_ms: float = 0.0


@dataclass
class DetectionAlert:
    """Alert generated by ML detector."""

    alert_id: str
    flow_id: str
    attack_category: str  # A1, A2, A4
    severity: str  # low, medium, high, critical
    confidence: float
    detection_time: float
    feature_vector: Dict
    action_taken: str = "none"
    timestamp: str = field(default_factory=lambda: datetime.now().isoformat())


# ─────────────────────────────────────────────────────────────
# Model Trainer
# ─────────────────────────────────────────────────────────────
class ModelTrainer:
    """Trains and persists ML models for intrusion detection."""

    FEATURE_COLUMNS = [
        "duration_ms",
        "total_pkts",
        "flow_bytes_per_sec",
        "flow_packets_per_sec",
        "pkt_len_mean",
        "pkt_len_std",
        "flag_syn",
        "flag_ack",
        "flag_fin",
        "flag_rst",
        "flag_psh",
        "flag_urg",
    ]

    def __init__(self, model_type: str = "isolation_forest"):
        self.model_type = model_type
        self.scaler = StandardScaler()
        self.model = self._build_model()
        self.is_trained = False

    def _build_model(self):
        """Build the selected ML model."""
        if self.model_type == "isolation_forest":
            return IsolationForest(
                n_estimators=100,
                contamination=0.1,
                max_samples="auto",
                random_state=42,
                n_jobs=-1,
            )
        elif self.model_type == "random_forest":
            return RandomForestClassifier(
                n_estimators=100,
                max_depth=10,
                min_samples_split=5,
                random_state=42,
                n_jobs=-1,
            )
        elif self.model_type == "hybrid":
            return {
                "isolation": IsolationForest(contamination=0.1, random_state=42),
                "classifier": RandomForestClassifier(n_estimators=50, random_state=42),
            }
        else:
            raise ValueError(f"Unknown model type: {self.model_type}")

    def train(self, X: np.ndarray, y: Optional[np.ndarray] = None):
        """Train the model on feature data."""
        X_scaled = self.scaler.fit_transform(X)

        if self.model_type == "hybrid":
            self.model["isolation"].fit(X_scaled)
            # Use isolation forest predictions as pseudo-labels for supervised training
            pseudo_labels = self.model["isolation"].predict(X_scaled)
            pseudo_labels = np.where(
                pseudo_labels == -1, 1, 0
            )  # -1=attack, 1=benign → 1=attack, 0=benign
            self.model["classifier"].fit(X_scaled, pseudo_labels)
        elif self.model_type == "isolation_forest":
            self.model.fit(X_scaled)
        else:
            if y is None:
                raise ValueError("Random Forest requires labeled data")
            self.model.fit(X_scaled, y)

        self.is_trained = True
        print(f"[TRAINER] {self.model_type} model trained on {X.shape[0]} samples")

    def predict(self, X: np.ndarray) -> Tuple[np.ndarray, np.ndarray]:
        """Predict on feature matrix. Returns (predictions, confidence scores)."""
        X_scaled = self.scaler.transform(X)

        if self.model_type == "isolation_forest":
            preds = self.model.predict(X_scaled)
            scores = self.model.score_samples(X_scaled)
            # Convert: -1=anomaly(attack), 1=benign → 1=attack, 0=benign
            preds = np.where(preds == -1, 1, 0)
            # Confidence from anomaly score (more negative = more anomalous)
            confidence = np.abs(scores)
            confidence = (confidence - confidence.min()) / (
                confidence.max() - confidence.min() + 1e-8
            )
            return preds, confidence

        elif self.model_type == "hybrid":
            iso_preds = self.model["isolation"].predict(X_scaled)
            clf_preds = self.model["classifier"].predict(X_scaled)
            clf_probs = self.model["classifier"].predict_proba(X_scaled)
            # Use hybrid: isolation forest for initial detection, RF for confidence
            combined_preds = np.where(iso_preds == -1, 1, clf_preds)
            confidence = clf_probs.max(axis=1)
            return combined_preds, confidence
        else:
            preds = self.model.predict(X_scaled)
            if hasattr(self.model, "predict_proba"):
                confidence = self.model.predict_proba(X_scaled).max(axis=1)
            else:
                confidence = np.ones(len(preds))
            return preds, confidence

    def save(self, path: str):
        """Save trained model and scaler."""
        os.makedirs(os.path.dirname(path), exist_ok=True)
        model_data = {
            "model_type": self.model_type,
            "scaler": self.scaler,
            "model": self.model,
            "is_trained": self.is_trained,
        }
        joblib.dump(model_data, path)
        print(f"[TRAINER] Model saved to {path}")

    def load(self, path: str):
        """Load trained model and scaler."""
        model_data = joblib.load(path)
        self.model_type = model_data["model_type"]
        self.scaler = model_data["scaler"]
        self.model = model_data["model"]
        self.is_trained = model_data["is_trained"]
        print(f"[TRAINER] Model loaded from {path}")


# ─────────────────────────────────────────────────────────────
# Real-time ML Detector Daemon
# ─────────────────────────────────────────────────────────────
class MLDetectorDaemon:
    """
    Real-time anomaly detection daemon.
    Reads Suricata eve.json, classifies flows, and takes action.
    """

    def __init__(
        self,
        model_path: str = None,
        model_type: str = "isolation_forest",
        eve_json_path: str = "data/suricata/eve.json",
        threshold: float = 0.7,
        action: str = "block",
    ):
        self.eve_json_path = eve_json_path
        self.threshold = threshold
        self.action = action
        self._lock = threading.Lock()
        self._running = False

        # Initialize model
        self.trainer = ModelTrainer(model_type=model_type)
        if model_path and os.path.exists(model_path):
            self.trainer.load(model_path)

        # Detection state
        self.alerts: List[DetectionAlert] = []
        self.flow_buffer = deque(maxlen=10000)
        self.stats = defaultdict(int)
        self._alert_id_counter = 0

        # Feature tracking for real-time classification
        self.recent_features = deque(maxlen=1000)

    def parse_eve_json(self, line: str) -> Optional[Dict]:
        """Parse a single line of Suricata eve.json."""
        try:
            event = json.loads(line.strip())
            return event
        except json.JSONDecodeError:
            return None

    def extract_features_from_event(self, event: Dict) -> Optional[FlowFeature]:
        """Extract flow features from Suricata eve.json event."""
        try:
            if event.get("event_type") != "flow":
                return None

            flow = event.get("flow", {})
            feature = FlowFeature(
                flow_id=flow.get("flow_id", ""),
                timestamp=event.get("timestamp", time.time()),
                duration_ms=flow.get("duration", 0) * 1000,
                total_fwd_pkts=flow.get("pkts_toserver", 0),
                total_bwd_pkts=flow.get("pkts_toclient", 0),
                total_pkts=flow.get("pkts_toserver", 0) + flow.get("pkts_toclient", 0),
                flow_bytes_per_sec=flow.get("bytes_toserver", 0)
                + flow.get("bytes_toclient", 0),
                flow_packets_per_sec=0,  # Calculated below
                pkt_len_mean=0,
                pkt_len_std=0,
                flag_syn=flow.get("syn_count", 0),
                flag_ack=flow.get("ack_count", 0),
                flag_fin=flow.get("fin_count", 0),
                flag_rst=flow.get("rst_count", 0),
                flag_psh=flow.get("psh_count", 0),
                flag_urg=flow.get("urg_count", 0),
            )

            # Calculate derived features
            elapsed = max(feature.duration_ms / 1000, 0.001)
            feature.flow_packets_per_sec = feature.total_pkts / elapsed
            if feature.duration_ms > 0:
                feature.flow_bytes_per_sec = (
                    flow.get("bytes_toserver", 0) + flow.get("bytes_toclient", 0)
                ) / elapsed

            return feature
        except Exception:
            return None

    def classify_flow(self, feature: FlowFeature) -> Tuple[str, float, str]:
        """
        Classify a single flow using the trained model.
        Returns: (prediction, confidence, attack_category)
        """
        if not self.trainer.is_trained:
            return "unknown", 0.0, "unknown"

        feature_vector = np.array(
            [
                [
                    feature.duration_ms,
                    feature.total_pkts,
                    feature.flow_bytes_per_sec,
                    feature.flow_packets_per_sec,
                    feature.pkt_len_mean,
                    feature.pkt_len_std,
                    feature.flag_syn,
                    feature.flag_ack,
                    feature.flag_fin,
                    feature.flag_rst,
                    feature.flag_psh,
                    feature.flag_urg,
                ]
            ]
        )

        preds, confidence = self.trainer.predict(feature_vector)
        pred = int(preds[0])
        conf = float(confidence[0])

        # Determine attack category based on feature patterns
        attack_category = self._categorize_attack(feature)

        if pred == 1 and conf >= self.threshold:
            return "attack", conf, attack_category
        elif pred == 1:
            return "suspicious", conf, attack_category
        else:
            return "benign", conf, "normal"

    def _categorize_attack(self, feature: FlowFeature) -> str:
        """Categorize attack type based on feature patterns."""
        # Heuristic categorization based on flow characteristics
        if feature.flag_syn > feature.flag_ack * 5 and feature.total_fwd_pkts > 100:
            return "A1a"  # Port scan
        if feature.flag_syn > 100 and feature.total_fwd_pkts > 500:
            return "A1"  # DoS flood
        if (
            feature.flag_syn > 0
            and feature.flag_ack == 0
            and feature.total_fwd_pkts < 5
        ):
            return "A4c"  # XSS/SQLi reconnaissance
        if feature.flow_bytes_per_sec > 1000000 and feature.total_fwd_pkts > 1000:
            return "A2d"  # Resource abuse
        return "A4"  # Default application attack

    def take_action(self, alert: DetectionAlert):
        """Take enforcement action (block IP via iptables)."""
        if self.action == "block":
            try:
                src_ip = alert.feature_vector.get("src_ip", "")
                if src_ip:
                    subprocess.run(
                        ["iptables", "-A", "INPUT", "-s", src_ip, "-j", "DROP"],
                        capture_output=True,
                        timeout=5,
                    )
                    alert.action_taken = f"blocked {src_ip}"
            except Exception as e:
                alert.action_taken = f"failed: {e}"
        elif self.action == "alert":
            alert.action_taken = "logged_only"
        elif self.action == "rate_limit":
            alert.action_taken = "rate_limited"

    def process_event(self, event: Dict) -> Optional[DetectionAlert]:
        """
        Process a single Suricata event end-to-end.
        Returns DetectionAlert if attack detected, None otherwise.
        """
        feature = self.extract_features_from_event(event)
        if feature is None:
            return None

        start = time.time()
        prediction, confidence, category = self.classify_flow(feature)
        feature.detection_time_ms = (time.time() - start) * 1000

        if prediction in ("attack", "suspicious"):
            self._alert_id_counter += 1
            alert = DetectionAlert(
                alert_id=f"ML-{self._alert_id_counter:06d}",
                flow_id=feature.flow_id,
                attack_category=category,
                severity=self._severity_from_confidence(confidence),
                confidence=confidence,
                detection_time=feature.detection_time_ms,
                feature_vector=feature.__dict__,
                timestamp=datetime.now().isoformat(),
            )

            if self.action != "none":
                self.take_action(alert)

            self.alerts.append(alert)
            self.stats["total_detections"] += 1

            if prediction == "attack":
                self.stats["confirmed_attacks"] += 1
            else:
                self.stats["suspicious_alerts"] += 1

            # Track latency
            if feature.detection_time_ms > 50:
                self.stats["latency_violations"] += 1

            return alert

        self.stats["benign_classified"] += 1
        return None

    def _severity_from_confidence(self, confidence: float) -> str:
        """Map confidence to severity level."""
        if confidence >= 0.9:
            return "critical"
        elif confidence >= 0.7:
            return "high"
        elif confidence >= 0.5:
            return "medium"
        else:
            return "low"

    def start(self, eve_json_path: str = None, batch_size: int = 100):
        """Start monitoring Suricata eve.json."""
        self._running = True
        self.eve_json_path = eve_json_path or self.eve_json_path

        print(
            f"[ML DETECTOR] Starting daemon (model: {self.trainer.model_type}, "
            f"threshold: {self.threshold})"
        )

        while self._running:
            if not os.path.exists(self.eve_json_path):
                time.sleep(1)
                continue

            try:
                with open(self.eve_json_path, "r") as f:
                    lines = f.readlines()

                for line in lines[-batch_size:]:
                    if not self._running:
                        break
                    event = self.parse_eve_json(line)
                    if event:
                        self.process_event(event)

                time.sleep(0.1)  # Polling interval

            except Exception as e:
                print(f"[ERROR] {e}", file=sys.stderr)
                time.sleep(1)

    def stop(self):
        """Stop the daemon."""
        self._running = False
        print(f"[ML DETECTOR] Stopped. Stats: {dict(self.stats)}")

    def get_detection_stats(self) -> Dict:
        """Return detection statistics."""
        total = self.stats.get("total_detections", 0)
        return {
            "total_detections": total,
            "confirmed_attacks": self.stats.get("confirmed_attacks", 0),
            "suspicious_alerts": self.stats.get("suspicious_alerts", 0),
            "benign_classified": self.stats.get("benign_classified", 0),
            "latency_violations": self.stats.get("latency_violations", 0),
            "avg_detection_latency_ms": (
                sum(a.detection_time_ms for a in self.alerts) / len(self.alerts)
                if self.alerts
                else 0
            ),
            "total_alerts": len(self.alerts),
        }

    def generate_report(self) -> Dict:
        """Generate comprehensive detection report."""
        stats = self.get_detection_stats()
        return {
            "report_timestamp": datetime.now().isoformat(),
            "model_type": self.trainer.model_type,
            "total_alerts": len(self.alerts),
            "statistics": stats,
            "alerts": [a.__dict__ for a in self.alerts[-100:]],  # Last 100
        }


